// Builds the Telugudanam museum Short from script.json into build/<slug>/:
// an Indian English voiceover, word captions, and screen recordings of the
// site's own tools (made by record.cjs) inside a browser window, in the site's
// own look. Render with `hyperframes render` there.
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CAPTION_TIMELINE, captionClips, display, esc, narrate, writeSoundtrack } from "../lib/shorts.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const BUILD = join(HERE, "build");
const W = 1080;
const H = 1920;
const MAX_SPEEDUP = 1.8; // a recording longer than its beat plays at most this much faster

// node build.mjs [--script script-glimpse.json]: the full walkthrough and the teaser share this build.
const scriptArg = process.argv.indexOf("--script");
const scriptFile = scriptArg === -1 ? "script.json" : process.argv[scriptArg + 1];
const script = JSON.parse(readFileSync(join(HERE, scriptFile), "utf8"));
const f = (x) => Number(x.toFixed(3));
const clip = (start, end, track) => `data-start="${f(start)}" data-duration="${f(end - start)}" data-track-index="${track}"`;
const seconds = (file) => Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString());

const out = join(BUILD, script.slug);
mkdirSync(join(out, "clips"), { recursive: true });
cpSync(join(HERE, "vendor"), join(out, "vendor"), { recursive: true });
cpSync(join(HERE, "museum.css"), join(out, "museum.css"));

// ---------- narration ----------

const segments = [
  { kind: "intro", text: script.hookSay, clip: script.hookClip, label: script.hookLabel ?? "Free website", big: script.hook },
  ...script.beats.map((b) => ({ kind: "beat", text: b.say, ...b })),
  { kind: "outro", text: script.outro },
];
const { endStart, total } = narrate(segments, { voice: script.voice, speed: script.speed, accent: script.accent, cacheDir: join(BUILD, ".tts") });
writeSoundtrack(segments, total, out, { music: script.music, seed: 2511 });

const scenes = segments.slice(0, -1).map((seg, i) => ({
  ...seg,
  from: i === 0 ? 0 : seg.start - 0.2,
  to: i === segments.length - 2 ? endStart : segments[i + 1].start - 0.2,
}));

// ---------- recordings, fitted to their beat ----------
// Longer than the beat: played faster (up to MAX_SPEEDUP), then cut.
// Shorter: the last frame is held.
for (const sc of scenes) {
  const src = join(HERE, "assets", `${sc.clip}.mp4`);
  const skip = sc.clipStart ?? 0; // seconds of the recording to skip
  const len = seconds(src) - skip;
  const want = sc.to - sc.from + 0.1;
  const rate = Math.min(Math.max(len / want, 1), MAX_SPEEDUP);
  const filters = [`setpts=PTS/${rate.toFixed(4)}`, `tpad=stop_mode=clone:stop_duration=${Math.max(0, want - len / rate + 0.2).toFixed(3)}`, "fps=30"];
  execFileSync("ffmpeg", ["-loglevel", "error", "-y", "-ss", String(skip), "-i", src, "-vf", filters.join(","), "-t", want.toFixed(3), "-an",
    "-c:v", "libx264", "-crf", "18", "-preset", "medium", "-pix_fmt", "yuv420p", "-movflags", "+faststart", join(out, "clips", `${sc.clip}.mp4`)]);
  sc.rate = rate;
}

// ---------- composition ----------

const cardHtml = scenes
  .map((sc, i) => {
    const big = display(sc.big);
    const size = i === 0 ? (script.hookSize ?? 76) : big.length <= 9 ? 132 : big.length <= 13 ? 108 : 88;
    return `      <div id="card-${i}" class="card clip" ${clip(sc.from, sc.to, 10)}>
        <div class="card-label">${esc(display(sc.label))}</div>
        <div class="card-big" style="font-size:${size}px">${esc(big)}</div>
      </div>`;
  })
  .join("\n");

const videoHtml = scenes
  .map((sc, i) => `      <video id="rec-${i}" class="rec clip" src="clips/${sc.clip}.mp4" muted playsinline ${clip(sc.from, sc.to, 20)}></video>`)
  .join("\n");

const captions = captionClips(segments, clip);
const e = script.end;
const html = `<!doctype html>
<!-- Generated by build.mjs from script.json. Edit those, not this file. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <script src="vendor/gsap.min.js"></script>
    <link rel="stylesheet" href="museum.css" />
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${f(total)}" data-width="${W}" data-height="${H}">
      <div id="bg" class="clip" ${clip(0, total, 0)}></div>
      <div id="window" class="clip" ${clip(0, endStart, 15)}>
        <div id="bar"><i></i><i></i><i></i><span>${esc(script.url)}</span></div>
      </div>
${videoHtml}
      <div id="progress-track" class="clip" ${clip(0, endStart, 6)}></div>
      <div id="progress" class="clip" ${clip(0, endStart, 7)}></div>
${cardHtml}
${captions.html}
      <div id="end-card" class="clip" ${clip(endStart, total, 30)}>
        <div id="end-kicker">Visit and explore</div>
        <div id="end-te">తెలుగుదనం</div>
        <div id="end-title">${esc(e.title)}</div>
        <div id="end-url">${esc(script.url)}</div>
        <ul id="end-lines">${e.lines.map((l) => `<li>${esc(l)}</li>`).join("")}</ul>
        <p id="end-small">${esc(e.small)}</p>
      </div>
      <audio id="soundtrack" src="soundtrack.wav" ${clip(0, total, 50)}></audio>
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
      const endStart = ${f(endStart)};
      tl.fromTo("#progress", { scaleX: 0 }, { scaleX: 1, duration: endStart, ease: "none" }, 0);
${scenes
  .map((sc, i) => (i ? `      tl.from("#card-${i}", { y: -30, opacity: 0, duration: 0.35, ease: "back.out(1.6)" }, ${f(sc.from)});` : ""))
  .join("\n")}
${CAPTION_TIMELINE}
      tl.from("#end-card > *", { y: 30, opacity: 0, duration: 0.45, stagger: 0.15, ease: "power3.out" }, endStart);

      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
`;
writeFileSync(join(out, "index.html"), html);
console.log(`${script.slug}: ${total.toFixed(1)}s, ${captions.count} caption groups`);
for (const sc of scenes) console.log(`  ${sc.clip.padEnd(10)} ${(sc.to - sc.from).toFixed(1)}s  x${sc.rate.toFixed(2)}`);
